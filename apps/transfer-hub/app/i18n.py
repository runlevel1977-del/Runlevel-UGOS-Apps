LANG_COOKIE = "transfer_hub_lang"


def normalize_lang(code: str | None) -> str | None:
    if not code:
        return None
    token = str(code).strip().lower().replace("_", "-")
    if token in STRINGS:
        return token
    primary = token.split("-", 1)[0].split("_", 1)[0]
    return primary if primary in STRINGS else None


def resolve_lang(
    accept_language: str | None = None,
    *,
    query_lang: str | None = None,
    cookie_lang: str | None = None,
) -> str:
    """User choice (query/cookie) beats env, NAS locale, then browser; default en."""
    for raw in (query_lang, cookie_lang):
        picked = normalize_lang(raw)
        if picked:
            return picked
    forced = normalize_lang(os.environ.get("TRANSFER_HUB_LANG", ""))
    if forced:
        return forced
    for var in ("LC_ALL", "LANG", "LC_MESSAGES"):
        picked = normalize_lang(os.environ.get(var) or "")
        if picked:
            return picked
    if accept_language:
        for part in accept_language.split(","):
            token = part.split(";")[0].strip()
            picked = normalize_lang(token)
            if picked:
                return picked
    return "en"


def lang_from_request(req) -> str:
    return resolve_lang(
        req.headers.get("Accept-Language"),
        query_lang=req.args.get("lang"),
        cookie_lang=req.cookies.get(LANG_COOKIE),
    )


def t(key: str, lang: str | None = None, **fmt: Any) -> str:
    lng = lang or "en"
    s = STRINGS.get(lng, STRINGS["en"]).get(key, STRINGS["en"].get(key, key))
    if fmt:
        try:
            return s.format(**fmt)
        except (KeyError, ValueError):
            return s
    return s


def bundle(lang: str) -> dict[str, str]:
    return dict(STRINGS.get(lang, STRINGS["en"]))


def get_lang() -> str:
    try:
        from flask import g

        return getattr(g, "lang", resolve_lang())
    except RuntimeError:
        return resolve_lang()


def supported_langs() -> list[str]:
    return list(LANG_LABELS.keys())

