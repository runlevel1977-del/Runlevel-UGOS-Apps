def _load_en_de() -> tuple[dict[str, str], dict[str, str]]:
    if STRINGS_JSON.is_file():
        data = json.loads(STRINGS_JSON.read_text(encoding="utf-8"))
        return dict(data["en"]), dict(data["de"])
    # Fallback: parse current i18n.py STRINGS
    ns: dict = {}
    raw = SRC.read_text(encoding="utf-8")
    partial = raw.split("LANG_COOKIE", 1)[0]
    if "STRINGS" not in partial:
        partial = raw.split("def normalize_lang", 1)[0]
    exec(compile(partial, "i18n_partial.py", "exec"), ns)
    strings = ns["STRINGS"]
    return dict(strings["en"]), dict(strings["de"])


