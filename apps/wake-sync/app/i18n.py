def env_lang() -> str:
    loc = " ".join(
        (os.environ.get(v) or "") for v in ("LANG", "LC_ALL", "LC_MESSAGES")
    ).lower()
    for code in ("de", "fr", "es", "it", "pl", "ru", "tr", "hr", "zh"):
        if code in loc:
            return code
    tz = (os.environ.get("TZ") or "").lower()
    tz_map = {
        "europe/berlin": "de",
        "europe/vienna": "de",
        "europe/zurich": "de",
        "europe/paris": "fr",
        "europe/brussels": "fr",
        "europe/madrid": "es",
        "europe/rome": "it",
        "europe/warsaw": "pl",
        "europe/moscow": "ru",
        "europe/istanbul": "tr",
        "europe/zagreb": "hr",
        "asia/shanghai": "zh",
        "asia/hong_kong": "zh",
        "asia/taipei": "zh",
    }
    if tz in tz_map:
        return tz_map[tz]
    return "en"


def normalize_lang(raw: str | None) -> str | None:
    if not raw:
        return None
    v = str(raw).strip().lower().replace("_", "-")
    if v in STRINGS:
        return v
    primary = v.split("-", 1)[0][:2]
    return primary if primary in STRINGS else None


def set_thread_lang(lang: str | None) -> None:
    if lang:
        _thread_lang.value = lang
    else:
        if hasattr(_thread_lang, "value"):
            del _thread_lang.value


def get_lang() -> str:
    tl = getattr(_thread_lang, "value", None)
    if tl:
        return tl
    try:
        from flask import g

        return getattr(g, "lang", "en")
    except RuntimeError:
        return env_lang()


def resolve_lang() -> str:
    """Alias used by job modules (Transfer Hub naming)."""
    return get_lang()


def lang_from_request(request) -> str:
    c = normalize_lang(request.cookies.get(LANG_COOKIE))
    if c:
        return c
    q = normalize_lang(request.args.get("lang"))
    if q:
        return q
    al = (request.headers.get("Accept-Language") or "").lower()
    for part in al.split(","):
        token = part.split(";", 1)[0].strip()
        picked = normalize_lang(token)
        if picked:
            return picked
    return env_lang()


def t(key: str, lang: str | None = None, **fmt: Any) -> str:
    lng = lang or get_lang()
    s = STRINGS.get(lng, STRINGS["en"]).get(key) or STRINGS["en"].get(key, key)
    if fmt:
        try:
            return s.format(**fmt)
        except (KeyError, ValueError):
            return s
    return s


def bundle(lang: str) -> dict[str, str]:
    return dict(STRINGS.get(lang, STRINGS["en"]))


def supported_langs() -> list[str]:
    return list(LANG_LABELS.keys())

