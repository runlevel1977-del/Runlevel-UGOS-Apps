  function normalizeLang(raw) {
    if (!raw) return null;
    const v = String(raw).trim().toLowerCase().replace(/_/g, "-");
    if (LANGS.indexOf(v) >= 0) return v;
    const primary = v.split("-", 1)[0].slice(0, 2);
    return LANGS.indexOf(primary) >= 0 ? primary : null;
  }

  function detectLang() {
    const stored = normalizeLang(localStorage.getItem(KEY));
    if (stored) return stored;
    const nav = String(navigator.language || navigator.userLanguage || "").toLowerCase();
    const picked = normalizeLang(nav);
    return picked || "en";
  }

  let lang = detectLang();

  function t(key, vars) {
    const table = STR[lang] || STR.en;
    let s = table[key] || (STR.en[key] || key);
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return s;
  }

  function fillLangSelect() {
    const sel = document.getElementById("lang-select");
    if (!sel) return;
    const previous = sel.value || lang;
    sel.innerHTML = "";
    LANGS.forEach((code) => {
      const opt = document.createElement("option");
      opt.value = code;
      opt.textContent = LABELS[code] || code;
      sel.appendChild(opt);
    });
    sel.value = LANGS.indexOf(previous) >= 0 ? previous : lang;
  }

  function applyI18n() {
    document.documentElement.lang = lang;
    fillLangSelect();
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const s = t(el.getAttribute("data-i18n"));
      if (el.tagName === "OPTION") el.text = s;
      else el.textContent = s;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    const sel = document.getElementById("lang-select");
    if (sel) sel.value = lang;
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });
  }

  function setLang(next) {
    const picked = normalizeLang(next) || "en";
    lang = picked;
    localStorage.setItem(KEY, lang);
    applyI18n();
    document.dispatchEvent(new CustomEvent("mf-lang"));
  }

  function fmtLocale() {
    return FMT[lang] || "en-GB";
  }

