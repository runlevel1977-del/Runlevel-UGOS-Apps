  function detectLang() {
    const stored = localStorage.getItem(KEY);
    if (stored === "de" || stored === "en") return stored;
    return String(navigator.language || "").toLowerCase().startsWith("de") ? "de" : "en";
  }

  let lang = detectLang();

  function t(key, vars) {
    const table = STR[lang] || STR.en;
    let s = table[key] || (STR.en[key] || key);
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return s;
  }

  function applyI18n() {
    document.documentElement.lang = lang === "de" ? "de" : "en";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const s = t(el.getAttribute("data-i18n"));
      if (el.tagName === "OPTION") el.text = s;
      else el.textContent = s;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });
  }

  function setLang(next) {
    lang = next === "de" ? "de" : "en";
    localStorage.setItem(KEY, lang);
    applyI18n();
    document.dispatchEvent(new CustomEvent("mf-lang"));
  }

  function fmtLocale() {
    return lang === "de" ? "de-DE" : "en-GB";
  }

  global.t = t;
  global.applyI18n = applyI18n;
  global.setLang = setLang;
  global.currentLang = function () { return lang; };
  global.fmtLocale = fmtLocale;
